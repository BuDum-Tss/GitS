"""Нормализация слов для полнотекстового поиска (ТЗ 04): нижний регистр, ё -> е, лёгкое снятие русских окончаний.

Это не морфологический анализатор, а дешёвая основа слова без зависимостей: «отпуске», «отпуска», «отпуском» дают
одну основу. Для FTS5 и для эмбеддера-заглушки используются одни и те же основы."""
import re

_WORD = re.compile(r"[a-zа-я0-9]+", re.IGNORECASE)

STOPWORDS = frozenset(
    "и в во не что он на я с со как а то все она так его но да ты к у же вы за бы по только ее мне было вот от меня "
    "еще нет о из ему теперь когда даже ну вдруг ли если уже или ни быть был него до вас нибудь опять уж вам ведь там "
    "потом себя ничего ей может они тут где есть надо ней для мы тебя их чем была сам чтоб без будто чего раз тоже "
    "себе под будет ж тогда кто этот того потому этого какой совсем ним здесь этом один почти мой тем чтобы нее "
    "кажется сейчас были куда зачем всех никогда можно при наконец два об другой хоть после над больше тот через эти "
    "нас про всего них какая много разве три эту моя впрочем хорошо свою этой перед иногда лучше чуть том нельзя "
    "такой им более всегда конечно всю между такое это".split())

# длинные окончания раньше коротких; основа после снятия не короче трёх букв
_SUFFIXES = tuple(sorted(set((
    "ившись", "ывшись", "ование", "ования", "ованию", "ованием", "ировать", "ировал", "ировала",
    "ениями", "ениям", "ениях", "ением", "ения", "ений", "ение", "ению",
    "ается", "ются", "ится", "ятся",
    "ому", "ему", "ого", "его", "ими", "ыми", "ами", "ями", "ией", "ием",
    "ов", "ев", "ей", "ом", "ем", "ам", "ям", "ах", "ях", "ою", "ею", "ую", "юю", "ая", "яя", "ое", "ее", "ие", "ые",
    "ий", "ый", "ой", "ых", "их", "ть", "ет", "ут", "ют", "ит", "ат", "ят", "ал", "ял", "ла", "ли", "ло", "ну", "ешь",
    "ись", "ся", "а", "я", "у", "ю", "ы", "и", "е", "о", "ь", "й",
)), key=len, reverse=True))


def stem(word: str) -> str:
    w = word.lower().replace("ё", "е")
    if len(w) < 5 or not re.search(r"[а-я]", w):
        return w
    for suf in _SUFFIXES:
        if w.endswith(suf) and len(w) - len(suf) >= 3:
            return w[: -len(suf)]
    return w


def tokens(text: str, drop_stop: bool = True) -> list[str]:
    """Основы слов текста по порядку (без стоп-слов)."""
    out = []
    for m in _WORD.finditer((text or "").lower().replace("ё", "е")):
        w = m.group(0)
        if drop_stop and w in STOPWORDS:
            continue
        out.append(stem(w))
    return out


def fts_body(text: str) -> str:
    """Что кладётся в индекс FTS5: основы через пробел."""
    return " ".join(tokens(text))


def fts_query(text: str) -> str:
    """Запрос FTS5: основы через OR, каждая в кавычках (экранирование). Пустая строка, если слов нет."""
    seen = dict.fromkeys(t for t in tokens(text) if t)
    return " OR ".join('"' + t.replace('"', '""') + '"' for t in seen)
