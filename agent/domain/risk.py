"""Политика риска инструмента (ТЗ 29, ARC-2): нужно ли спрашивать разрешение человека. Чистая функция.

Правило из `router` (ТЗ-правило безопасности): опасное действие, инструмент «ask», а также публичное действие без
самоподтверждения, если в настройках включено подтверждение публикаций в Telegram.
"""


def needs_ask(danger, risk: str, self_confirming: bool, telegram_confirm: bool) -> bool:
    """True, если перед действием нужно разрешение. `telegram_confirm` имеет смысл только для публичных действий
    без самоподтверждения; вызывающий код читает настройку лениво, только в этом случае."""
    return bool(danger) or risk == "ask" or (risk == "public" and not self_confirming and bool(telegram_confirm))
