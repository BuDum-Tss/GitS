"""Правила по тексту реплики (ТЗ 29, ARC-2): просьба замолчать и похоже ли сообщение на просьбу что-то сделать.

Оба правила живут здесь, чтобы не дублироваться в `attention` и `router`. Это два разных правила, поэтому две разные
выражения: «замолчи» сопоставляется со всей короткой фразой, а глаголы-просьбы ищутся внутри текста по основам.
"""
import re

# Короткая фраза целиком: «замолчи», «пожалуйста, стоп», «хватит болтать» (ATT-18)
_STOP_RE = re.compile(r"^\W*(пожалуйста[\W]+)?(замолчи|замолчите|помолчи|помолчите|молчи|заткнись|тихо|"
                      r"хватит( болтать| говорить| трепаться)?|прекрати( говорить| болтать)?|стоп|stop|shut up)\W*"
                      r"(пожалуйста\W*)?$", re.I)

# Глаголы-просьбы: по ним решается, нужен ли планировщик вообще. Болтовня идёт мимо него,
# чтобы отвечать сразу, без лишнего вызова модели.
_VERBS = ("напиш", "включ", "выключ", "найд", "сдела", "покаж", "запомн", "забуд", "отправ", "откр",
          "закр", "замолч", "помолч", "запост", "опублик", "посмотр", "провер", "удал", "созд",
          "скач", "установ", "запуст", "запуск", "стартуй", "поигра", "останов", "постав", "заказ", "купи", "переключ", "отключ",
          "поруч", "клод", "claude", "попроси", "отвлека", "нажм", "кликн", "набер", "напечата", "прокрут", "вспомн", "помниш", "запиши", "закаж", "оплат", "забронир", "отмен", "перезапуст", "обнови", "загруз", "видиш", "слыши", "подсматр", "подслуш", "слушай", "прочит", "сохран", "измени", "поменяй")


def looks_like_stop(text: str) -> bool:
    """Короткая просьба замолчать: быстрый путь без модели (ATT-18)."""
    return len(text) <= 40 and bool(_STOP_RE.match(text.strip()))


EPISODE_KINDS = ("episode.summary", "episode.ended")


def think_route(*, origin: str, kind: str, **_) -> bool:
    """Маршрут `think` (ТЗ 30, IMP-4, IMP-10): напоминание себе, итог разговора, итог эпизода. Остальные события копятся во
    входящей очереди и уходят размышлению пачкой (`app/inbox.py`). Мысль сама размышление не запускает (нет петли)."""
    if kind == "self.thought":
        return False
    if origin == "self":
        return kind in ("self.reminder", "self.after_conversation", "self.work_tick")
    return kind.endswith(EPISODE_KINDS)
