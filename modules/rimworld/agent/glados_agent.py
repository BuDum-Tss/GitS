async def run_turn(memory_context: str, chat_signals: list[str],
                   hours_passed: float | None = None,
                   just_loaded: bool = False,
                   urgent: list[str] | None = None,
                   order: str | None = None,
                   situation: str | None = None,
                   changes: list[str] | None = None,
                   mode: str = "observe", brief: str = "") -> dict:
    """Быстрый реактивный/проактивный ход — исполняет задачи, реагирует на события.
    order — прямое требование игрока из чата (важнее планов), urgent — тревожные события прямо сейчас."""
    parts = []
    if changes:
        parts.append("=== ЧТО ИЗМЕНИЛОСЬ с твоего прошлого хода ===\n" + "\n".join(f"- {c}" for c in changes))
    if situation:
        parts.append("=== СИТУАЦИЯ ===\n" + situation)
    if order:
        parts.append(
            "=== ПРИКАЗ ИГРОКА (важнее любых твоих планов) ===\n" + order + "\n"
            "Выполни это СЕЙЧАС конкретными действиями инструментов. Не откладывай «на следующий этап», не "
            "объясняй игроку, что он торопится, не спорь: если он прав, действуй; если приказ невыполним, "
            "коротко скажи почему.")
    if urgent:
        parts.append(
            "=== БОЕВАЯ ТРЕВОГА: происходит прямо сейчас ===\n" + "\n".join(f"- {u}" for u in urgent) + "\n"
            "Игра поставлена на паузу, чтобы ты успела отдать приказы. Действуй быстро, не больше 8-10 вызовов: "
            "(1) get_colony_state: кто где, кто ранен, где враги (threats); (2) вооружи колонистов, у которых нет "
            "оружия (equip_item, оружие ищи в colony.forbidden_items/на складе, при необходимости unforbid_item); "
            "(3) draft_pawns способных бойцов, attack_target на ближайшего врага; раненых уведи в укрытие/на "
            "кровать; (4) в конце кратко скажи, что сделала. Колонисты без оружия не должны идти в бой в рукопашную.")
    if just_loaded:
        parts.append(
            "=== СОБЫТИЕ ===\n"
            "Колония только что загрузилась (новая игра или загрузка сохранения). "
            "Осмотрись через get_colony_state и отреагируй как персонаж, который "
            "только что очнулся/вернулся к эксперименту — что-то вроде \"так, что "
            "тут у нас, на чём мы остановились\", с конкретными деталями (кто жив, "
            "что построено, чего не хватает). Это НЕ рутинная проверка тика."
        )
    elif hours_passed is not None:
        parts.append(f"=== ВРЕМЯ ===\nС прошлой проверки прошло {hours_passed} игровых часов.")
    if memory_context.strip():
        parts.append(memory_context)
    if brief:                                                       # ТЗ 11e: события, важное, шаг, инструменты-запросы
        parts.append(brief)
    if chat_signals:
        parts.append("=== OBSERVER INPUT (chat, 12% predictive accuracy) ===")
        parts.extend(f"  - {s}" for s in chat_signals[-10:])
    parts.append("Analyze the current colony situation and take any necessary actions.")
    import game_modes
    parts.insert(0, game_modes.prompt_for(mode))
    tools = [_T + n for n in game_modes.tools_for(mode)]            # в режиме только его инструменты (около 15-30 вместо 95)
    return await _run_agent(SYSTEM_PROMPT, "\n".join(parts), tools, mode=mode, contour="turn")


