MODEL = "claude-haiku-4-5-20251001"


TURN_TIMEOUT = 300   # секунд на один ход любого контура: зависший ход не должен вечно держать игру


def _game_model() -> str:
    """Модель игровых контуров: из настройки game_model (haiku по умолчанию)."""
    import settings
    return "sonnet" if settings.load().get("game_model") == "sonnet" else MODEL


async def _run_agent(system_prompt: str, prompt: str, allowed_tools: list[str],
                     cwd: str | None = None, permission_mode: str = "acceptEdits",
                     restrict: bool = True, timeout: float = TURN_TIMEOUT, mode: str = "", contour: str = "game") -> dict:
    """restrict=True (по умолчанию) — жёстко ограничивает доступные инструменты
    списком allowed_tools через параметр tools SDK. Без этого allowed_tools
    сам по себе НЕ ограничивает доступность — только снимает подтверждение,
    а Read/Write/Edit/Bash остаются доступны по умолчанию (tools=None даёт
    полный набор встроенных инструментов). Единственный контур, которому
    действительно нужен полный доступ — самоулучшение (restrict=False)."""
    agent_kwargs: dict = dict(
        system_prompt=system_prompt,
        model=_game_model(),
        mcp_servers={
            "rimworld": {
                "command": sys.executable,
                "args": [_MCP_SCRIPT],
                **({"env": {**os.environ, "GLADOS_MODE": mode}} if mode else {}),      # сервер сам скрывает чужие инструменты
            }
        },
        allowed_tools=allowed_tools,
        permission_mode=permission_mode,
    )
    if restrict:
        agent_kwargs["tools"] = allowed_tools
    if cwd:
        agent_kwargs["cwd"] = cwd
    if _CLI_PATH:
        agent_kwargs["cli_path"] = _CLI_PATH

    options = ClaudeAgentOptions(**agent_kwargs)

    commentary = ""
    actions: list[str] = []
    success = False

    if claude_quota.blocked():
        return {"commentary": "", "actions": [], "success": False, "timed_out": False, "quota": True}
    started = time.time()
    outcome = {"timed_out": False}

    async def _consume():
        nonlocal commentary, success
        async for message in query(prompt=prompt, options=options):
            if isinstance(message, AssistantMessage):
                for block in message.content:
                    if hasattr(block, "text") and block.text:
                        if claude_quota.note(block.text):
                            continue          # «you've hit your session limit»: не реплика
                        commentary = block.text.strip()
                    elif hasattr(block, "name"):
                        actions.append(block.name)
                        logger.info(f"[ход +{time.time() - started:.0f}с] {block.name.replace('mcp__rimworld__', '')}")
            elif isinstance(message, ResultMessage):
                usage_report.push_result(message, contour)      # core.claude_usage, источник rimworld.<контур>
                success = message.subtype == "success"
                if not success:
                    logger.warning(f"Ход завершился с итогом {message.subtype}: {str(getattr(message, 'result', ''))[:200]}")

    try:
        await asyncio.wait_for(_consume(), timeout)
    except asyncio.TimeoutError:
        outcome["timed_out"] = True
        logger.error(f"Ход не уложился в {timeout:.0f}с и прерван (сделано вызовов: {len(actions)}, "
                     f"последний: {actions[-1] if actions else 'нет'})")
    except Exception as e:
        if claude_quota.note(str(e)):
            logger.warning("Лимит Claude исчерпан, ход пропущен")
        else:
            logger.error(f"GLaDOS agent error: {e}", exc_info=True)

    return {"commentary": commentary, "actions": actions, "success": success,
            "quota": claude_quota.blocked(), **outcome}
